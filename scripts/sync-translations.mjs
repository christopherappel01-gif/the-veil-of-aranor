/**
 * Build-time localization maintenance. Run after editing any dialogue, story, or UI.
 * DEEPL_AUTH_KEY is used by the developer ONLY; never shipped to browsers.
 * --check rejects stale/missing translations. --sync fills them with DeepL.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..');
const output=path.join(root,'public/translations.generated.js');
const storeFile=path.join(root,'translations.catalog.json');
const check=process.argv.includes('--check');
const sourceFiles=['public/app.js','server.js','public/index.html'];
const sha=s=>crypto.createHash('sha256').update(s).digest('hex').slice(0,16);
const read=x=>fs.readFileSync(path.join(root,x),'utf8');
const src=sourceFiles.map(x=>read(x));
// Literal extractor: HTML visible text and JS quoted phrases. Dynamic strings assembled
// from templates require their own named keys; the report tracks missing work.
const phrases=new Set();
for(let k=0;k<2;k++){
 const source=src[k];
 const pattern=/(?:'((?:\\.|[^'\\])*)'|"((?:\\.|[^"\\])*)")/g;let m;
 while((m=pattern.exec(source))){let s=m[1]??m[2];
  s=s.replace(/\\(['"\\])/g,'$1').trim();
  if(s.length<12||s.length>1200||!/[a-z]{3,}/i.test(s)||!/\s/.test(s))continue;
  if(/[<>]|\b(?:const|function|return|className|document|socket|console|undefined)\b|[{};]/.test(s))continue;
  if(/^(?:https?:|\/|\.|#|data:)/.test(s))continue;
  phrases.add(s);
 }
}
const html=src[2];for(const m of html.matchAll(/>([^<>]+)</g)){
 const s=m[1].trim();if(s.length>=5&&/[a-z]{3,}/i.test(s)&&!s.includes('${'))phrases.add(s);
}
// Source is key: any changed source text becomes a new missing entry.
let catalog={};if(fs.existsSync(storeFile))catalog=JSON.parse(fs.readFileSync(storeFile,'utf8'));
const langs=['nl','fr','de'];
const entries={};for(const s of [...phrases].sort())entries[s]=catalog.entries?.[s]||{hash:sha(s),nl:'',fr:'',de:''};
// Merge existing authored V9 translations and German starter translations from the
// game for initial coverage; ignore JS escapes by reading its runtime object via VM.
import vm from 'node:vm';
let authored={};try{
 const app=src[0];const start=app.indexOf('const localizedText=');const end=app.indexOf('const translateZones=',start);
 const literal=app.slice(start,end);
 const context={window:{LOST_EXPEDITION_I18N:{}},Object};
 vm.runInNewContext(literal.replace('const localizedText=','globalThis.localizedText='),context,{timeout:1000});
 authored=context.localizedText||{};
}catch(e){console.warn('Authored translations could not be imported:',e.message)}
for(const [phrase,translations] of Object.entries(entries))for(const lang of langs){if(!translations[lang]&&authored[lang]?.[phrase])translations[lang]=authored[lang][phrase];}
const missing=[];for(const phrase of Object.keys(entries))for(const lang of langs)if(!entries[phrase][lang])missing.push({phrase,lang});
async function translate(lang,batch){
 const key=process.env.DEEPL_AUTH_KEY;if(!key)throw new Error('DEEPL_AUTH_KEY is required to generate translations');
 const endpoint=process.env.DEEPL_API_URL||(key.endsWith(':fx')?'https://api-free.deepl.com/v2/translate':'https://api.deepl.com/v2/translate');
 const params=new URLSearchParams({target_lang:lang.toUpperCase(),source_lang:'EN'});
 for(const s of batch)params.append('text',s);
 const r=await fetch(endpoint,{method:'POST',headers:{Authorization:'DeepL-Auth-Key '+key,'Content-Type':'application/x-www-form-urlencoded'},body:params});
 if(!r.ok)throw new Error(`DeepL status ${r.status}: ${(await r.text()).slice(0,200)}`);
 const json=await r.json();if(json.translations?.length!==batch.length)throw new Error('Incomplete translation response');
 return json.translations.map(t=>t.text);
}
if(!check&&process.env.DEEPL_AUTH_KEY){
 for(const lang of langs){const pending=Object.keys(entries).filter(s=>!entries[s][lang]);
  for(let i=0;i<pending.length;i+=25){const batch=pending.slice(i,i+25),translated=await translate(lang,batch);batch.forEach((s,j)=>entries[s][lang]=translated[j]);}
  console.log(`${lang}: ${pending.length} new translations`);
 }
}
const remaining=[];for(const phrase of Object.keys(entries))for(const lang of langs)if(!entries[phrase][lang])remaining.push({phrase,lang});
if(!check){
 fs.writeFileSync(storeFile,JSON.stringify({sourceFiles,entries},null,2)+'\n');
 const out={};for(const lang of langs){out[lang]={};for(const [phrase,row] of Object.entries(entries))if(row[lang])out[lang][phrase]=row[lang];}
 fs.writeFileSync(output,'// Generated by npm run translations:sync. Do not edit.\nwindow.LOST_EXPEDITION_I18N='+JSON.stringify(out)+';\n');
}
console.log(`${Object.keys(entries).length} translatable source strings; ${remaining.length} untranslated language entries.`);
if(remaining.length){console.log('Examples:',remaining.slice(0,8).map(v=>`${v.lang}: ${v.phrase.slice(0,70)}`).join('\n'));if(check)process.exitCode=1;}
