import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'..');
const src=fs.readFileSync(path.join(root,'public/app.js'),'utf8');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'translations.catalog.json'),'utf8')).entries;
const begin=src.indexOf('function sceneLocaleText('),end=src.indexOf('function refreshSceneLocale(',begin);
assert(begin>=0&&end>begin);
const dictionary={};for(const [en,row] of Object.entries(catalog))if(row.nl)dictionary[en]=row.nl;
const context={selectedLanguage:'en',window:{LOST_EXPEDITION_I18N:{nl:dictionary}},scenes:{intro:{title:'The Resolute',mission:'Something has appeared beyond the edge of every reliable chart. Decide what matters before night closes in.',text:['For eighteen days the Resolute has sailed west in search of Aranor, a continent erased from maps eight centuries ago. Most sailors think you are chasing a legend; the expedition’s backers are no longer quite so certain.'],choices:[['light','Study the strange light','Support · Normal (6)']]}},esc:(x)=>String(x)};
vm.createContext(context);
vm.runInContext(src.slice(begin,end)+';globalThis.expose={localizedScene,sceneLocaleText};',context);
const initial=JSON.stringify(context.scenes.intro);
const english=context.expose.localizedScene('intro','en');const dutch=context.expose.localizedScene('intro','nl');
assert.equal(english.title,'The Resolute');assert.equal(dutch.title,'De Resolute');
assert.notEqual(english.text[0],dutch.text[0]);assert.equal(dutch.choices[0][1],'Bestudeer het vreemde licht');
assert.equal(JSON.stringify(context.scenes.intro),initial,'Canonical source scene mutated');
assert.equal(context.expose.localizedScene('intro','en').title,'The Resolute','English was not restored');
assert.equal(context.expose.sceneLocaleText('Unknown untranslated text','nl'),'Unknown untranslated text');
console.log('PASS: explicit NL/EN scene render, dialogue and choices, canonical state immutable, fallback defined');
